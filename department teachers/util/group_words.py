#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""师资同组分类页词表 (probe_site 与 fix_loop 共用)

背景: 师资入口页/列表页下常挂职称分类子页(教授/副教授/讲师/博士后/院士/
兼职/双聘/退休…)。历史缺陷: probe 的 BFS 与信号验证看不见这些弱信号页,
fix_loop 曾只抓其中一页(上大马院只抓教授页 24 人, 缺副教授/讲师/博士后)。

确定性文本正则比 LLM/信号可靠: 分类页链接文本即分类名, 且稳定。
_USER_KW/_USER_EXC 的取舍依据见 data_quality_review.md 用户 4 案例:
- 交大计院 szdw.html 6 子链接: 教师名录/院士学者/国家级人才/兼职和双聘教师/
  退休教师 全部要; 人才招聘 不要
- 交大环院 /faculty 5 子菜单: 师资概况/教师名录/博士后 要; 环院师声(宣传)/
  人才招聘 不要
- 交大药院 szdw.html 13 子链接: 师资名录/人才名录/长聘序列/常规序列/博导介绍/
  兼职教授/双聘教授/行业导师/在站博士后 要; 师资概况/院士风采/人才招聘 不要
- 上大马院 szdw 4 页: 教授/副教授/讲师/博士后 全要
"""
import re

# 命中 → 视为师资分类子页(并入采集多入口)
GROUP_KW = re.compile(
    r"教授|讲师|博士后|院士|国家级人才|省部级人才|人才称号|师资名录|教师名录|"
    r"教师名单|教工名录|教师目录|师资团队|师资概况|教师概况|兼职|双聘|客座|退休|荣休|"
    r"离休|返聘|长聘|常规序列|行业导师|博导|硕导|助教|"
    r"博士生导师|硕士生导师|导师名录|企业导师|学术硕士导师|专业硕士导师|杰出人才|实践导师|校企导师|"
    r"硕士导师|博士导师|"
    r"教师队伍|导师队伍|全职教师|在职教师|全体教师|全部教师|专任教师|"
    # 2026-09-16 北科工程技术研究院实锤: "知名学者/学术梯队" 是机构型单位
    # 的师资栏目名(人员页跳领导页, 名单在学者/梯队子页)
    r"知名学者|学术梯队|学者|梯队|"
    # 2026-09-16 太理双创实锤: "双创教指委/校外导师/校内双创导师" 分类页
    r"校外导师|校内导师|教指委|"
    # 2026-09-16 辽大外院实锤: 词表漏了最常见的"师资队伍"本身(4 系名单页
    # "英语系师资队伍简介"全漏) + 湖师大"研究骨干介绍"子页
    r"师资队伍|师资力量|教授名录|研究骨干|骨干介绍|科研骨干")

# 命中 → 排除(宣传/招聘/概况/行政类, 用户明示过滤)
# 2026-08-31 用户指令: 取消"概况"过滤 — 师资概况(西交材料 mse szgk.htm)
# 是真实名单页, 此前被 EXC 排除导致名单页漏采; 学院概况/学校概况类导航页
# 由 find_faculty_page 的 PRECISE/NOISE 机制另行把关
GROUP_EXC = re.compile(
    r"招聘|招贤|招才|诚聘|简介|风采|宣传|新闻|动态|通知|公告|"
    r"党建|党务|行政|工会|团委|领导|寄语|联系|English|师声|导师风采")

# 链接文本级判断: 是"师资分类子页"候选?
def is_group_link(text):
    """len 2-24 + 命中 KW + 未命中 EXC → True。
    2026-09-16 辽大外院实锤: "英语系师资队伍简介"是真实名单文章页 — 含师资/
    教师/导师/教授/队伍词的简介(概况)页是名单页, EXC 只滤纯栏目页。"""
    if not text or len(text) > 24 or len(text) < 2:
        return False
    _bad = GROUP_EXC.search(text) and not re.search(r"师资|教师|导师|教授|队伍", text)
    return bool(GROUP_KW.search(text)) and not _bad
